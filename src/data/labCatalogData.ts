export function getLocalLabTests(): PredefinedLabTest[] {
  const saved = localStorage.getItem('hc_hospital_lab_tests_v2');
  if (saved) {
    try {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    } catch (e) {}
  }
  return PREDEFINED_LAB_TESTS;
}

export function saveLocalLabTests(tests: PredefinedLabTest[]): void {
  localStorage.setItem('hc_hospital_lab_tests_v2', JSON.stringify(tests));
}
